-- KURO ID: immutable public identifier for every KUROLAB account.
-- auth.users remains the canonical internal key; profiles.kuro_id is the user-facing ID.

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS kuro_id text;

ALTER TABLE public.profiles
  ALTER COLUMN kuro_id
  SET DEFAULT (
    'KURO-' || upper(substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 16))
  );

-- Backfill every existing account before enforcing NOT NULL.
UPDATE public.profiles
SET kuro_id = 'KURO-' || upper(substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 16))
WHERE kuro_id IS NULL OR btrim(kuro_id) = '';

ALTER TABLE public.profiles
  ALTER COLUMN kuro_id SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS profiles_kuro_id_uidx
  ON public.profiles (kuro_id);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'profiles_kuro_id_format_check'
      AND conrelid = 'public.profiles'::regclass
  ) THEN
    ALTER TABLE public.profiles
      ADD CONSTRAINT profiles_kuro_id_format_check
      CHECK (kuro_id ~ '^KURO-[A-F0-9]{16}$');
  END IF;
END
$$;

CREATE OR REPLACE FUNCTION public.enforce_immutable_kuro_id()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
  IF TG_OP = 'INSERT' THEN
    -- Always generate on the server. Never accept a client-supplied identifier.
    NEW.kuro_id :=
      'KURO-' || upper(substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 16));
  ELSIF NEW.kuro_id IS DISTINCT FROM OLD.kuro_id THEN
    RAISE EXCEPTION USING
      ERRCODE = '42501',
      MESSAGE = 'KURO ID is permanent and cannot be changed.';
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS profiles_enforce_immutable_kuro_id ON public.profiles;

CREATE TRIGGER profiles_enforce_immutable_kuro_id
  BEFORE INSERT OR UPDATE OF kuro_id
  ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.enforce_immutable_kuro_id();

COMMENT ON COLUMN public.profiles.kuro_id IS
  'Permanent public KURO identifier. Generated by the database; auth.users.id remains the internal canonical key.';
